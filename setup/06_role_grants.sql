-- ============================================================
-- 06_role_grants.sql
-- Creates FINANCE_ADMIN role with full access to all
-- FINANCIAL_VARIANCE objects, Streamlit app, and Cowork dashboard.
-- ============================================================

USE ROLE ACCOUNTADMIN;

-- Create role
CREATE ROLE IF NOT EXISTS FINANCE_ADMIN
  COMMENT = 'Full access to FINANCIAL_VARIANCE database, Streamlit app, and Cowork dashboard';

-- Grant to current user
GRANT ROLE FINANCE_ADMIN TO USER somirza;

-- Warehouse
GRANT USAGE ON WAREHOUSE FINANCE_WH TO ROLE FINANCE_ADMIN;

-- Database
GRANT USAGE ON DATABASE FINANCIAL_VARIANCE TO ROLE FINANCE_ADMIN;

-- All schemas
GRANT USAGE ON ALL SCHEMAS IN DATABASE FINANCIAL_VARIANCE TO ROLE FINANCE_ADMIN;

-- Bronze: SELECT on all tables
GRANT SELECT ON ALL TABLES IN SCHEMA FINANCIAL_VARIANCE.BRONZE TO ROLE FINANCE_ADMIN;

-- Silver: SELECT on all dynamic tables
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA FINANCIAL_VARIANCE.SILVER TO ROLE FINANCE_ADMIN;

-- Gold: SELECT on dynamic tables, SELECT/INSERT/UPDATE on regular tables (BVA_COMMENTARY)
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;

-- Stage (Streamlit files)
GRANT READ ON ALL STAGES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;

-- Stored procedures (AI commentary + anomaly explanation)
GRANT USAGE ON ALL PROCEDURES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;

-- Streamlit app
GRANT USAGE ON STREAMLIT FINANCIAL_VARIANCE.GOLD.FINANCIAL_VARIANCE_ANALYSIS TO ROLE FINANCE_ADMIN;

-- Cortex LLM functions
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE FINANCE_ADMIN;

-- Cowork dashboard publishing
GRANT MANAGE ARTIFACT PUBLICATION TO ROLE FINANCE_ADMIN;

-- Future grants (auto-cover new objects)
GRANT SELECT ON FUTURE TABLES IN SCHEMA FINANCIAL_VARIANCE.BRONZE TO ROLE FINANCE_ADMIN;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FINANCIAL_VARIANCE.SILVER TO ROLE FINANCE_ADMIN;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;
GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA FINANCIAL_VARIANCE.GOLD TO ROLE FINANCE_ADMIN;
